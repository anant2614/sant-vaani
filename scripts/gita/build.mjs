#!/usr/bin/env node
// Builds the Gita for the app (apps/mobile/assets/db/gita.db, plus
// gita.json for the web preview, which has no SQLite) and the database
// (supabase/seed/01_gita.sql) from the vendored IAST source.
// Run with: npm run gita:build
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { toDevanagari } from './devanagari.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
export const SQL_PATH = join(root, 'supabase/seed/01_gita.sql');
export const DB_PATH = join(root, 'apps/mobile/assets/db/gita.db');
export const JSON_PATH = join(root, 'apps/mobile/assets/db/gita.json');
/** Bump when the shape or text of gita.db changes, so the app replaces its copy. */
export const DB_VERSION = 1;

export function readGita() {
  const source = JSON.parse(readFileSync(join(here, 'source/gita-iast.json'), 'utf8'));
  const names = JSON.parse(readFileSync(join(here, 'chapters.json'), 'utf8'));
  const chapters = [];
  const verses = [];

  for (const name of names) {
    const raw = source[String(name.number)];
    const numbers = Object.keys(raw)
      .filter((key) => /^\d+$/.test(key))
      .map(Number)
      .sort((a, b) => a - b);
    chapters.push({ ...name, verse_count: numbers.length });

    for (const number of numbers) {
      const parts = raw[String(number)].replace(/\|+$/, '').split('|');
      const speaker = parts.length === 3 ? parts.shift() : null;
      if (parts.length !== 2) throw new Error(`${name.number}.${number} does not have two half-lines`);
      const [first, second] = parts.map((p) => p.trim());
      verses.push({
        chapter: name.number,
        verse: number,
        speaker_sa: speaker ? toDevanagari(speaker) : null,
        speaker_iast: speaker,
        sanskrit: `${toDevanagari(first)} ।\n${toDevanagari(second)} ॥`,
        transliteration: `${first.replace(/;/g, '')} |\n${second.replace(/;/g, '')} ||`,
        meaning_en: null,
        meaning_hi: null,
      });
    }
  }
  return { chapters, verses };
}

const sqlText = (value) => (value === null ? 'null' : `'${value.replace(/'/g, "''")}'`);

export function seedSql({ chapters, verses }) {
  const lines = [
    '-- Generated by scripts/gita/build.mjs from scripts/gita/source/gita-iast.json. Do not edit.',
    "insert into public.scriptures (id, name_en, name_hi, name_sa) values ('gita', 'Bhagavad Gita', 'श्रीमद्भगवद्गीता', 'श्रीमद्भगवद्गीता')",
    '  on conflict (id) do nothing;',
    '',
    'insert into public.chapters (scripture_id, number, name_sa, name_iast, name_en, verse_count) values',
    chapters
      .map(
        (c) =>
          `  ('gita', ${c.number}, ${sqlText(c.name_sa)}, ${sqlText(c.name_iast)}, ${sqlText(c.name_en)}, ${c.verse_count})`,
      )
      .join(',\n'),
    '  on conflict (scripture_id, number) do nothing;',
    '',
    'insert into public.verses (scripture_id, chapter, verse, speaker_sa, speaker_iast, sanskrit, transliteration, meaning_en, meaning_hi) values',
    verses
      .map(
        (v) =>
          `  ('gita', ${v.chapter}, ${v.verse}, ${sqlText(v.speaker_sa)}, ${sqlText(v.speaker_iast)}, ${sqlText(v.sanskrit)}, ${sqlText(v.transliteration)}, null, null)`,
      )
      .join(',\n'),
    '  on conflict (scripture_id, chapter, verse) do nothing;',
    '',
  ];
  return lines.join('\n');
}

export function writeSqlite({ chapters, verses }, path = DB_PATH) {
  if (existsSync(path)) rmSync(path);
  const db = new DatabaseSync(path);
  try {
    db.exec(`
      pragma journal_mode = delete;
      create table chapters (
        number integer primary key,
        name_sa text not null,
        name_iast text not null,
        name_en text not null,
        verse_count integer not null
      );
      create table verses (
        chapter integer not null references chapters (number),
        verse integer not null,
        speaker_sa text,
        speaker_iast text,
        sanskrit text not null,
        transliteration text not null,
        meaning_en text,
        meaning_hi text,
        primary key (chapter, verse)
      ) without rowid;
      pragma user_version = ${DB_VERSION};
    `);
    const addChapter = db.prepare(
      'insert into chapters (number, name_sa, name_iast, name_en, verse_count) values (?, ?, ?, ?, ?)',
    );
    const addVerse = db.prepare(
      'insert into verses (chapter, verse, speaker_sa, speaker_iast, sanskrit, transliteration, meaning_en, meaning_hi) values (?, ?, ?, ?, ?, ?, ?, ?)',
    );
    db.exec('begin');
    for (const c of chapters) addChapter.run(c.number, c.name_sa, c.name_iast, c.name_en, c.verse_count);
    for (const v of verses) {
      addVerse.run(v.chapter, v.verse, v.speaker_sa, v.speaker_iast, v.sanskrit, v.transliteration, v.meaning_en, v.meaning_hi);
    }
    db.exec('commit');
    db.exec('vacuum');
  } finally {
    db.close();
  }
}

/** The same tables as gita.db, one object per row. */
export function webJson({ chapters, verses }) {
  return `${JSON.stringify({ version: DB_VERSION, chapters, verses })}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const gita = readGita();
  writeFileSync(SQL_PATH, seedSql(gita));
  writeSqlite(gita);
  writeFileSync(JSON_PATH, webJson(gita));
  console.log(`Wrote ${gita.verses.length} verses to ${SQL_PATH}, ${DB_PATH} and ${JSON_PATH}.`);
}
